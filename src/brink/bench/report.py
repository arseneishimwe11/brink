"""Write benchmark tables to docs/RESULTS.md and log runs in docs/EXPERIMENTS.md."""

from __future__ import annotations

import json
import subprocess
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from brink.bench.metrics import summarise

RESULTS_HEADER = """# Brink benchmark results

Generated by `brink bench`. Do not edit by hand; rerun the command instead.
Every number below comes from the run named in its section.

How to read these tables:
- "Flagged" counts true undercuts that Brink reported at their location.
  The bracket is a 95% confidence interval, which is wide when the count is small.
- "False alarms" are reported undercuts or overhangs where the scene has none.
- Results on the `test` split come from scenes never used for tuning.
- Synthetic scenes are not real ground. They show what the method can do under
  controlled conditions, not what it will do at a real site.
"""


def git_commit() -> str:
    try:
        return subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True, check=True
        ).stdout.strip()
    except Exception:
        return "unknown"


def _rate(cell: dict[str, Any]) -> str:
    if not cell["n"]:
        return "none in set"
    lo, hi = cell["ci95"]
    return f"{cell['detected']}/{cell['n']} ({100 * cell['rate']:.0f}%, {100 * lo:.0f}-{100 * hi:.0f})"


def _num(value: float, fmt: str = ".2f", unit: str = "") -> str:
    return "n/a" if value != value else f"{value:{fmt}}{unit}"


def group_summaries(records: list[dict[str, Any]], keys: tuple[str, ...]) -> dict[tuple, dict[str, Any]]:
    groups: dict[tuple, list[dict[str, Any]]] = {}
    for r in records:
        groups.setdefault(tuple(r[k] for k in keys), []).append(r)
    return {k: summarise(v) for k, v in groups.items()}


def hazard_table(summaries: dict[tuple, dict[str, Any]], key_names: tuple[str, ...]) -> str:
    head = [*key_names, "Captures", "Undercut >= 20 cm flagged", "20-30 cm", "30-50 cm", ">= 50 cm",
            "Under 20 cm flagged", "Controls with a false alarm", "False alarms per capture",
            "Depth error, median", "Depth error, 90th pct", "Depth bias"]
    rows = []
    for key, s in summaries.items():
        rows.append([
            *[str(k) for k in key], f"{s['reconstructed']}/{s['captures']}",
            _rate(s["undercut_ge_20cm"]), _rate(s["undercut_20_30cm"]), _rate(s["undercut_30_50cm"]),
            _rate(s["undercut_ge_50cm"]), _rate(s["undercut_lt_20cm"]),
            f"{s['control_with_false_alarm']}/{s['control_captures']}",
            _num(s["false_alarms_per_capture"]),
            _num(s["depth_err_median_abs"], ".3f", " m"), _num(s["depth_err_p90_abs"], ".3f", " m"),
            _num(s["depth_err_bias"], "+.3f", " m"),
        ])
    return _table(head, rows)


def slope_table(summaries: dict[tuple, dict[str, Any]], key_names: tuple[str, ...]) -> str:
    head = [*key_names, "Faces measured", "Slope error, median", "90th pct", "Worst", "Within 5 deg",
            "Height error, median", "Height error, 90th pct", "Over-steep call correct", "Time per capture, median"]
    rows = []
    for key, s in summaries.items():
        rows.append([
            *[str(k) for k in key], f"{s['slope_n']}/{s['reconstructed']}",
            _num(s["slope_err_median_abs"], ".2f", " deg"), _num(s["slope_err_p90_abs"], ".2f", " deg"),
            _num(s["slope_err_max_abs"], ".2f", " deg"), f"{s['slope_within_5deg']}/{s['slope_n']}",
            _num(100 * s["height_err_rel_median_abs"], ".1f", "%"), _num(100 * s["height_err_rel_p90_abs"], ".1f", "%"),
            f"{s['oversteep_correct']}/{s['oversteep_n']}", _num(s["time_median_s"], ".1f", " s"),
        ])
    return _table(head, rows)


def _table(head: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(head) + " |", "|" + "|".join(["---"] * len(head)) + "|"]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(lines)


