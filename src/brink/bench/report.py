def save_section(bench_dir: Path, name: str, title: str, command: str, body: str, records: list[dict[str, Any]]) -> None:
    """Store one benchmark section so RESULTS.md can be rebuilt from all of them."""
    bench_dir.mkdir(parents=True, exist_ok=True)
    (bench_dir / f"{name}.records.jsonl").write_text("\n".join(json.dumps(r) for r in records) + "\n")
    meta = {
        "name": name, "title": title, "command": command, "body": body,
        "commit": git_commit(), "when": datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC"),
    }
    (bench_dir / f"{name}.section.json").write_text(json.dumps(meta, indent=2))


def write_results(bench_dir: Path, results_path: Path, order: list[str]) -> None:
    parts = [RESULTS_HEADER]
    sections = {p.name.removesuffix(".section.json"): json.loads(p.read_text()) for p in bench_dir.glob("*.section.json")}
    for name in [n for n in order if n in sections] + sorted(n for n in sections if n not in order):
        meta = sections[name]
        parts.append(
            f"\n## {meta['title']}\n\nCommand: `{meta['command']}`  \n"
            f"Run: {meta['when']}, code at commit `{meta['commit']}`\n\n{meta['body']}\n"
        )
    results_path.write_text("\n".join(parts))


def log_experiment(path: Path, title: str, command: str, body: str, notes: str = "") -> None:
    stamp = datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")
    if not path.exists():
        path.write_text(
            "# Brink experiment log\n\nNewest entries at the bottom. Each entry gives the command that\n"
            "produced its numbers and the code version it ran on.\n"
        )
    entry = f"\n## {stamp}: {title}\n\nCommand: `{command}`  \nCode: commit `{git_commit()}` plus any uncommitted changes\n\n{body}\n"
    if notes:
        entry += f"\n{notes}\n"
    with path.open("a") as fh:
        fh.write(entry)
